#!/usr/bin/env python3
"""gen_example_110.py -- GENERATE the schema v1.10 good example and its X32 sabotage.

[B144] (docs/design/gate_shape_v14.md 3.7): rule `v1.10-group` judges a
`substitution` row at `iterations >= 1`. A substitution record is one
iteration x five trials, so the example needs five dense trials per row,
which is not hand-edit material; and the sabotage in `bad/` must be a
ONE-field mutation of a record that otherwise validates, so both come from
here and `--check` pins them byte for byte (make check-schema).

Built FROM the 1.9 substitution example beside it (nothing is re-stamped:
that file stays at 1.9 with its `v1.4-group` block, so check-schema proves
X32 is versioned):

  * GOOD  `subst-example@0.1__..._20261025T120000Z.jsonl` -- schema 1.10, the
    `p-5b` pattern on two subjects (acc-main, acc-small), 5 trials each, all
    clean: the block (rule `v1.10-group`, computed by the HARNESS's own
    derivation) judges 2 rows in 1 group, `agree`. The `p-7` compile row
    `unsupported-by-declaration` is kept.
  * BAD   `bad/x32-v110-subst-claims-agree.jsonl` -- the same record with BOTH
    rows' trials 2 and 4 slow (1.6x): the group disagrees (d = 2 of n = 2),
    but the block is left claiming the clean example's `agree`. Only X32
    can see it -- X31 holds (the verdict follows the stamped counts), and a
    1.9 record with these rows would be unjudged.

Usage:
    python3 schema/examples/gen_example_110.py            # (re)write both
    python3 schema/examples/gen_example_110.py --check    # exit 1 on drift
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "schema"))

from pcrecbench.reduce import judge_trial_agreement   # noqa: E402  the harness's derivation
import validate as V                                   # noqa: E402  the shared validator

SOURCE = os.path.join(
    HERE, "subst-example@0.1__example-subst_1.0.0_global-caps-nosimd__example-box"
          "__20261024T120000Z.jsonl")
BAD_NAME = "x32-v110-subst-claims-agree.jsonl"
TIMESTAMP = "2026-10-25T12:00:00Z"
SUBJECTS = (("acc-main", 320000000, 410000000, 295000000),
            ("acc-small", 1000000, 1300000, 920000))


def dumps(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def load_source():
    with open(SOURCE, encoding="utf-8") as fh:
        lines = [ln for ln in fh.read().split("\n") if ln.strip()]
    return json.loads(lines[0]), [json.loads(ln) for ln in lines[1:]]


def build(slow):
    """-> (setup, rows) with `slow` trials of every match row at 1.6x."""
    setup, src = load_source()
    setup["schema_version"] = "1.10"
    setup["run"]["timestamp"] = TIMESTAMP
    setup["run"]["run_id"] = "example-run-0110"
    setup["run"]["command_line"] = [
        "python3", "-m", "pcrecbench", "quick", "--subbench", "subst-example",
        "--trials", "5"]
    setup["note"] = (
        "SYNTHETIC EXAMPLE (schema v1.10, GENERATED by schema/examples/"
        "gen_example_110.py from the 1.9 substitution example) -- every value is "
        "INVENTED. Five one-iteration trials of case `5b` on two subjects: under "
        "rule `v1.10-group` a substitution row is judged at iterations >= 1; "
        "case `7` has no expression in this engine (a compile row "
        "`unsupported-by-declaration`). No engine was run; the reporter "
        "excludes `synthetic` records.")
    setup["subjects"] = [
        {"bytes_offered": b, "n_subjects": 1, "role": "single",
         "sha256": ("%064x" % (i + 1)), "subject_id": sid}
        for i, (sid, b, _ns, _ob) in enumerate(SUBJECTS)]
    compile_rows = [r for r in src if r["kind"] == "compile"]
    rows = list(compile_rows)
    for sid, nbytes, ns, out_bytes in SUBJECTS:
        for t in range(1, 6):
            v = int(round(ns * (1.6 if t in slow else 1.0 + 0.004 * (t % 3))))
            rows.append({
                "kind": "match", "match_outcome": "matched-as-expected",
                "pattern_id": "p-5b", "regime": "substitution",
                "subject_id": sid, "trial": t,
                "subst": {"case": "5b", "gate": "agrees", "nsubst": nbytes // 8,
                          "out_bytes": out_bytes,
                          "out_sha256": "1e51cbe4206098b712fe563bf304fd3f30e13a7a403e043e390990afe9f2a10e"},
                "timing": {"bytes_processed": nbytes, "elapsed_ns": v,
                           "iterations": 1}})
    for i, r in enumerate(rows, start=1):
        r["seq"] = i
    return setup, rows


def finish(setup, rows):
    setup["record_id"] = V.derive_record_id(setup)
    row_lines = [dumps(r) for r in rows]
    setup["content_hash"] = {"algorithm": "sha256",
                             "value": V.compute_content_hash(setup, row_lines)}
    return "\n".join([dumps(setup)] + row_lines) + "\n"


def main(argv):
    check = "--check" in argv
    # GOOD: clean trials, the block by the harness's derivation
    setup, rows = build(slow=())
    setup["trial_agreement"] = judge_trial_agreement(rows)
    assert setup["trial_agreement"]["verdict"] == "agree", setup["trial_agreement"]
    assert setup["trial_agreement"]["rule"] == "v1.10-group"
    assert setup["trial_agreement"]["rows_judged"] == 2, setup["trial_agreement"]
    good_block = json.loads(json.dumps(setup["trial_agreement"]))
    good_text = finish(setup, rows)
    good_path = os.path.join(HERE, setup["record_id"] + ".jsonl")
    # BAD: the rows disagree (the judge says so), the block still says agree
    bsetup, brows = build(slow=(2, 4))
    judged = judge_trial_agreement(brows)
    assert judged["verdict"] == "disagree" and judged["groups_disagreeing"] == 1, judged
    bsetup["trial_agreement"] = good_block
    bad_text = finish(bsetup, brows)
    bad_path = os.path.join(HERE, "bad", BAD_NAME)
    status = 0
    for path, text in ((good_path, good_text), (bad_path, bad_text)):
        if check:
            try:
                with open(path, encoding="utf-8") as fh:
                    committed = fh.read()
            except OSError:
                print("gen_example_110: %s is MISSING" % path, file=sys.stderr)
                status = 1
                continue
            if committed != text:
                print("gen_example_110: %s differs from what this generator "
                      "produces; regenerate it" % path, file=sys.stderr)
                status = 1
            else:
                print("gen_example_110: OK -- %s reproduces byte for byte"
                      % os.path.basename(path))
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print("gen_example_110: wrote %s" % path)
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
