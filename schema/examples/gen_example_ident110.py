#!/usr/bin/env python3
"""gen_example_ident110.py -- GENERATE the schema v1.10 TWO-HASH example and its X46 sabotage.

[B145] (BD13 amendment): from 1.10 a compile row that carries
`program_sha256` (normalization v2) carries `program_sha256_v3` too.

Built FROM the 1.8 boolean-grain example beside it (it stays at 1.8 and
keeps its one hash, which is what shows X46 is versioned):

  * GOOD  `boolgrain-example@0.1__..._20261025T120000Z.jsonl` -- schema 1.10,
    the compile row carries BOTH hashes, the `program_sha256_v3` pair declared
    with type `sha256`.
  * BAD   `bad/x46-v3-absent-on-110-compile-row.jsonl` -- the same record with
    the v3 member removed from the compile row (the declaration stays): only
    X46 can see it (X15 reads only members that are present).

Usage:
    python3 schema/examples/gen_example_ident110.py            # (re)write both
    python3 schema/examples/gen_example_ident110.py --check    # exit 1 on drift
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "schema"))

from pcrecbench.reduce import judge_trial_agreement   # noqa: E402
import validate as V                                   # noqa: E402

SOURCE = os.path.join(
    HERE, "boolgrain-example@0.1__example-boolscan_1.0.0_block-nosom-nocaps-simd__"
          "example-box__20261012T120000Z.jsonl")
BAD_NAME = "x46-v3-absent-on-110-compile-row.jsonl"
TIMESTAMP = "2026-10-25T12:00:00Z"
V3 = "1e1e1e1e" * 8


def dumps(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def build(with_v3):
    with open(SOURCE, encoding="utf-8") as fh:
        lines = [ln for ln in fh.read().split("\n") if ln.strip()]
    setup, rows = json.loads(lines[0]), [json.loads(ln) for ln in lines[1:]]
    setup["schema_version"] = "1.10"
    setup["run"]["timestamp"] = TIMESTAMP
    setup["run"]["run_id"] = "example-run-0145"
    setup["note"] = (
        "SYNTHETIC EXAMPLE (schema v1.10, GENERATED by schema/examples/"
        "gen_example_ident110.py from the 1.8 boolean-grain example) -- every "
        "value is INVENTED. One addition over its source: the `program_sha256_v3` "
        "pair (type `sha256`, BD13 amendment, [B145]) declared and carried on the "
        "compile row beside `program_sha256`. No engine was run; the reporter "
        "excludes `synthetic` records.")
    setup["testee"]["engine_metadata_declaration"]["program_sha256_v3"] = {
        "description": "v3-normalized program hash (illustrative); compared only "
                       "with another v3 value, through pcrecbench/identity.py",
        "scope": "pattern",
        "source": "(illustrative) tools/program_identity.py normalization v3",
        "type": "sha256"}
    for r in rows:
        if r["kind"] == "compile" and with_v3:
            r["engine_metadata"]["program_sha256_v3"] = V3
    setup["trial_agreement"] = judge_trial_agreement(rows)
    return setup, rows


def finish(setup, rows):
    setup["record_id"] = V.derive_record_id(setup)
    row_lines = [dumps(r) for r in rows]
    setup["content_hash"] = {"algorithm": "sha256",
                             "value": V.compute_content_hash(setup, row_lines)}
    return "\n".join([dumps(setup)] + row_lines) + "\n"


def main(argv):
    check = "--check" in argv
    gs, gr = build(True)
    good_text = finish(gs, gr)
    good_path = os.path.join(HERE, gs["record_id"] + ".jsonl")
    bs, br = build(False)
    bad_text = finish(bs, br)
    bad_path = os.path.join(HERE, "bad", BAD_NAME)
    status = 0
    for path, text in ((good_path, good_text), (bad_path, bad_text)):
        if check:
            try:
                with open(path, encoding="utf-8") as fh:
                    committed = fh.read()
            except OSError:
                print("gen_example_ident110: %s is MISSING" % path, file=sys.stderr)
                status = 1
                continue
            if committed != text:
                print("gen_example_ident110: %s differs from what this generator "
                      "produces; regenerate it" % path, file=sys.stderr)
                status = 1
            else:
                print("gen_example_ident110: OK -- %s reproduces byte for byte"
                      % os.path.basename(path))
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print("gen_example_ident110: wrote %s" % path)
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
