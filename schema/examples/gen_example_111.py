#!/usr/bin/env python3
"""gen_example_111.py -- GENERATE the schema v1.11 good example and its sabotages.

[B148] L1 (docs/design/unusual_set_v1.md v0.2 7.4): the `call-stream`
regime, `match.stream`, `testee.assist`, rule `v1.11-group` and rules
X47-X53. A call-stream record is five one-iteration trials per row (one
iteration = one full replay of the stream), which is not hand-edit material,
and every sabotage in `bad/` must be a small mutation of a record that
otherwise validates, so all of them come from here and `--check` pins them
byte for byte (make check-schema).

Built FROM the 1.10 substitution example beside it (nothing is re-stamped:
that file stays at 1.10 with its `v1.10-group` block):

  * GOOD `unusual-example@0.1__example-stream_1.0.0_calls-caps-nosimd_assist-v01
    __example-box__20261027T120000Z.jsonl` -- schema 1.11, an ASSISTED config
    (`config_extra` `assist-v01`, `testee.assist` listing `va-tenant`), three
    patterns: `va-tenant` (requires-vars; 2 host-refused calls per replay),
    `cscan` (recursion; the working-storage high-water pair on its rows, and a
    `deep` subject on which one call gives up on a named limit) and `va-term`,
    a NOT-CAPABLE member (a compile row `unsupported-by-declaration` whose
    `declaration_ref` carries the count). The block (rule `v1.11-group`,
    computed by the HARNESS's own derivation) judges the two timed rows.
  * BAD, one file per rule (each named for it, check_rules.py), listed in
    `SABOTAGES` below with what it changes.

Usage:
    python3 schema/examples/gen_example_111.py            # (re)write all
    python3 schema/examples/gen_example_111.py --check    # exit 1 on drift
"""

import copy
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "schema"))

from pcrecbench.reduce import judge_trial_agreement   # noqa: E402  the harness's derivation
import validate as V                                   # noqa: E402  the shared validator

SOURCE = os.path.join(
    HERE, "subst-example@0.1__example-subst_1.0.0_global-caps-nosimd__example-box"
          "__20261025T120000Z.jsonl")
TIMESTAMP = "2026-10-27T12:00:00Z"
LIMIT = "PCRE2_ERROR_HEAPLIMIT"


def dumps(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def load_source():
    with open(SOURCE, encoding="utf-8") as fh:
        lines = [ln for ln in fh.read().split("\n") if ln.strip()]
    return json.loads(lines[0])


def pattern(pid, text, tags):
    return {"canonical_sha256": sha(text), "canonical_text": text,
            "hazard_class": "none", "pattern_id": pid, "size_class": "tiny",
            "tags": tags, "variant": None}


def build():
    """-> (setup, rows), the GOOD record before its block and hashes."""
    setup = load_source()
    setup["schema_version"] = "1.11"
    setup.pop("trial_agreement", None)
    setup["run"]["timestamp"] = TIMESTAMP
    setup["run"]["run_id"] = "example-run-0111"
    setup["run"]["command_line"] = [
        "python3", "-m", "pcrecbench", "run", "--subbench", "unusual-example",
        "--trials", "5"]
    setup["note"] = (
        "SYNTHETIC EXAMPLE (schema v1.11, GENERATED by schema/examples/"
        "gen_example_111.py from the 1.10 substitution example) -- every value "
        "is INVENTED. Five one-iteration replays of two call streams under rule "
        "`v1.11-group`; an ASSISTED config (`assist-v01`) whose `va-term` "
        "member is NOT-CAPABLE (budget exceeded, a compile row "
        "`unsupported-by-declaration`); one `cscan` subject gives up on a named "
        "limit. No engine was run; the reporter excludes `synthetic` records.")
    setup["subbench"] = {
        "content_hash": sha("unusual-example@0.1"), "id": "unusual-example",
        "objective": "SYNTHETIC: exercise the call-stream regime's record shape.",
        "regimes": ["call-stream"],
        "source_ref": "schema/examples only -- not a real sub-bench",
        "version": "0.1"}
    t = setup["testee"]
    t["engine_name"] = "example-stream"
    t["engine_mode"] = "calls"
    t["config_extra"] = "assist-v01"
    t["build_flags"] = "SYNTHETIC EXAMPLE ONLY -- no engine named example-stream exists."
    t["binary"] = {"path": "/example/example-stream", "sha256": sha("example-stream")}
    t["assist"] = {"assist_version": "v01",
                   "members": [{"member": "va-tenant", "tokens": 212, "lines": 31,
                                "sha256": sha("assist va-tenant")}]}
    t["engine_metadata_declaration"] = {
        "deep_mem_bytes": {"type": "integer", "scope": "match",
                           "source": "the untimed high-water pass (unusual_set_v1.md 6.4)"},
        "deep_mem_method": {"type": "string", "scope": "match",
                            "source": "the method that took deep_mem_bytes (X52)"}}
    t["testee_id"] = V.derive_testee_id(t)
    setup["patterns"] = [
        pattern("va-tenant", "^${tenant}-[0-9]{4} (?:ERROR|WARN) ",
                ["family-vars", "requires-vars", "requires-unusual-va-tenant"]),
        pattern("cscan", "\\G(?&items)\\}\\)(?(DEFINE)(?<items>[^{}]*+(?:\\{(?&items)\\}[^{}]*+)*+))",
                ["family-recursion", "requires-recursion"]),
        pattern("va-term", "(?i)\\b${term:?}\\b",
                ["family-vars", "requires-vars", "requires-unusual-va-term"]),
    ]
    setup["subjects"] = [
        {"bytes_offered": 65536, "n_subjects": 1, "role": "single",
         "sha256": sha("s-lines"), "subject_id": "s-lines"},
        {"bytes_offered": 262144, "n_subjects": 1, "role": "single",
         "sha256": sha("s-c"), "subject_id": "s-c"},
        {"bytes_offered": 4096, "n_subjects": 1, "role": "single",
         "sha256": sha("s-deep"), "subject_id": "s-deep"},
    ]
    rows = [
        {"artifact_bytes": 4096, "compile_outcome": "compiled",
         "cost": {"phases": [{"elapsed_ns": 900000, "name": "compile"}], "total_ns": 900000},
         "cost_class": "eager-jit", "diagnostic": None, "kind": "compile",
         "pattern_id": "va-tenant", "trial": 1},
        {"artifact_bytes": 8192, "compile_outcome": "compiled",
         "cost": {"phases": [{"elapsed_ns": 1200000, "name": "compile"}], "total_ns": 1200000},
         "cost_class": "eager-jit", "diagnostic": None, "kind": "compile",
         "pattern_id": "cscan", "trial": 1},
        {"compile_outcome": "unsupported-by-declaration", "cost_class": "eager-jit",
         "declaration_ref": ("bench/unusual/assists/assists.tsv:3 tokens=412 "
                             "budget=300 (synthetic)"),
         "diagnostic": None, "kind": "compile", "pattern_id": "va-term", "trial": 1},
    ]
    streams = (
        ("va-tenant", "s-lines", 2000, 61440, 1490, 508, 2, 0, 41000000),
        ("cscan", "s-c", 512, 190000, 500, 12, 0, 0, 23000000),
    )
    for pid, sid, calls, seg, m, nm, rf, gu, ns in streams:
        for tr in range(1, 6):
            row = {"kind": "match", "match_outcome": "matched-as-expected",
                   "pattern_id": pid, "regime": "call-stream",
                   "subject_id": sid, "trial": tr,
                   "stream": {"calls": calls, "segment_bytes": seg, "matched": m,
                              "nomatch": nm, "refused": rf, "gave_up": gu,
                              "results_sha256": sha("results %s %s" % (pid, sid))},
                   "timing": {"bytes_processed": seg,
                              "elapsed_ns": int(ns * (1.0 + 0.004 * (tr % 3))),
                              "iterations": 1}}
            if pid == "cscan":
                row["engine_metadata"] = {"deep_mem_bytes": 1 << 20,
                                          "deep_mem_method": "counting-alloc"}
            rows.append(row)
    for tr in range(1, 6):
        rows.append({
            "kind": "match", "match_outcome": "gave-up", "pattern_id": "cscan",
            "regime": "call-stream", "subject_id": "s-deep", "trial": tr,
            "diagnostic": "call 1 of 1: %s (-63) at the 1 GiB cap" % LIMIT,
            "stream": {"calls": 1, "segment_bytes": 4096, "matched": 0,
                       "nomatch": 0, "refused": 0, "gave_up": 1,
                       "first_limit": LIMIT,
                       "results_sha256": sha("results cscan s-deep")}})
    return setup, rows


def finish(setup, rows, block=None):
    rows = [dict(r) for r in rows]
    for i, r in enumerate(rows, start=1):
        r["seq"] = i
    setup = copy.deepcopy(setup)
    setup["trial_agreement"] = block if block is not None else judge_trial_agreement(rows)
    setup["testee"]["testee_id"] = V.derive_testee_id(setup["testee"])
    setup["record_id"] = V.derive_record_id(setup)
    row_lines = [dumps(r) for r in rows]
    setup.pop("content_hash", None)
    setup["content_hash"] = {"algorithm": "sha256",
                             "value": V.compute_content_hash(setup, row_lines)}
    return setup["record_id"], "\n".join([dumps(setup)] + row_lines) + "\n"


def _row(rows, pid, sid, trial):
    for r in rows:
        if r["kind"] == "match" and r["pattern_id"] == pid \
                and r["subject_id"] == sid and r["trial"] == trial:
            return r
    raise KeyError((pid, sid, trial))


# --------------------------------------------------------------- sabotages
# Each takes (setup, rows) deep copies and mutates them; `finish` restamps
# the hashes (and recomputes the block unless the mutation pins one), so
# the ONLY rule a file breaks is the one it is named for (plus, where the
# mutation is a version change, the rules that version also implies).

def x47_absent(setup, rows):
    del _row(rows, "va-tenant", "s-lines", 3)["stream"]


def x47_other_regime(setup, rows):
    setup["subbench"]["regimes"].append("short-subject-search")
    for tr in range(1, 6):
        _row(rows, "cscan", "s-deep", tr)["regime"] = "short-subject-search"


def x48_off_by_one(setup, rows):
    _row(rows, "cscan", "s-c", 2)["stream"]["calls"] += 1


def x49_gave_up_but_matched(setup, rows):
    st = _row(rows, "va-tenant", "s-lines", 4)["stream"]
    st["matched"] -= 1
    st["gave_up"] = 1


def x49_diagnostic_silent(setup, rows):
    _row(rows, "cscan", "s-deep", 2)["diagnostic"] = "the engine gave up"


def x50_token_without_object(setup, rows):
    del setup["testee"]["assist"]


def x50_duplicate_member(setup, rows):
    mem = setup["testee"]["assist"]["members"]
    mem.append(dict(mem[0]))


def x52_bytes_without_method(setup, rows):
    del _row(rows, "cscan", "s-c", 1)["engine_metadata"]["deep_mem_method"]


def x52_method_guess(setup, rows):
    _row(rows, "cscan", "s-c", 5)["engine_metadata"]["deep_mem_method"] = "guess"


def x53_refused_on_cscan(setup, rows):
    st = _row(rows, "cscan", "s-c", 3)["stream"]
    st["nomatch"] -= 3
    st["refused"] = 3


def x53_empty_denominator(setup, rows):
    _row(rows, "va-tenant", "s-lines", 1)["stream"]["segment_bytes"] = 0


def x47_on_a_110_record(setup, rows):
    # the call-stream regime stamped 1.10: X47's version half (X50/X51 also
    # fire -- the assist and the rule are 1.11 things too)
    setup["schema_version"] = "1.10"


SABOTAGES = (
    ("x47-stream-absent-on-call-stream-row.jsonl", x47_absent),
    ("x47-stream-on-other-regime.jsonl", x47_other_regime),
    ("x47-call-stream-on-110-record.jsonl", x47_on_a_110_record),
    ("x48-stream-counts-off-by-one.jsonl", x48_off_by_one),
    ("x49-gave-up-count-but-matched.jsonl", x49_gave_up_but_matched),
    ("x49-diagnostic-does-not-name-limit.jsonl", x49_diagnostic_silent),
    ("x50-assist-token-without-object.jsonl", x50_token_without_object),
    ("x50-assist-duplicate-member.jsonl", x50_duplicate_member),
    ("x52-deep-mem-bytes-without-method.jsonl", x52_bytes_without_method),
    ("x52-deep-mem-method-unknown.jsonl", x52_method_guess),
    ("x53-refused-on-a-non-vars-pattern.jsonl", x53_refused_on_cscan),
    ("x53-segment-bytes-zero.jsonl", x53_empty_denominator),
)
X51_NAME = "x51-v111-group-on-110-record.jsonl"
X51_SOURCE = os.path.join(
    HERE, "subst-example@0.1__example-subst_1.0.0_global-caps-nosimd__example-box"
          "__20261025T120000Z.jsonl")


def x51_text():
    """The 1.10 substitution example with its block's rule re-labelled
    `v1.11-group` (and recomputed under it -- identical integers, since
    the record has no call-stream row): only the version pairing is wrong."""
    with open(X51_SOURCE, encoding="utf-8") as fh:
        lines = [ln for ln in fh.read().split("\n") if ln.strip()]
    setup = json.loads(lines[0])
    rows = [json.loads(ln) for ln in lines[1:]]
    setup["trial_agreement"] = judge_trial_agreement(rows, rule="v1.11-group")
    row_lines = [dumps(r) for r in rows]
    setup.pop("content_hash", None)
    setup["content_hash"] = {"algorithm": "sha256",
                             "value": V.compute_content_hash(setup, row_lines)}
    return "\n".join([dumps(setup)] + row_lines) + "\n"


def main(argv):
    check = "--check" in argv
    setup, rows = build()
    rid, good = finish(setup, rows)
    block = json.loads(good.split("\n")[0])["trial_agreement"]
    assert block["rule"] == "v1.11-group" and block["verdict"] == "agree", block
    assert block["rows_judged"] == 2 and block["rows_unjudged"] == 1, block
    outputs = [(os.path.join(HERE, rid + ".jsonl"), good)]
    for name, mutate in SABOTAGES:
        s2, r2 = copy.deepcopy(setup), copy.deepcopy(rows)
        mutate(s2, r2)
        outputs.append((os.path.join(HERE, "bad", name), finish(s2, r2)[1]))
    outputs.append((os.path.join(HERE, "bad", X51_NAME), x51_text()))
    status = 0
    for path, text in outputs:
        if check:
            try:
                with open(path, encoding="utf-8") as fh:
                    committed = fh.read()
            except OSError:
                print("gen_example_111: %s is MISSING" % path, file=sys.stderr)
                status = 1
                continue
            if committed != text:
                print("gen_example_111: %s differs from what this generator "
                      "produces; regenerate it" % path, file=sys.stderr)
                status = 1
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print("gen_example_111: wrote %s" % path)
    if check and status == 0:
        print("gen_example_111: OK -- the 1.11 example and %d sabotages reproduce "
              "byte for byte" % (len(outputs) - 1))
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
