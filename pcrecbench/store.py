"""store.py -- the record store: the path rule, the never-clobber rule, and
the index (OD-B6, harness contract 4).

    store/
      machines.tsv                       the machine registry (env.py, 6.5)
      index.tsv                          regenerated by `pcrecbench index`
      records/<subbench>@<version>/<testee_id>/<record_id>.jsonl

The FILE NAME IS THE RECORD ID (record_schema.md 2), so the tree is
self-describing: a record can be identified from its path alone, and
`validate.py --check-filename` (rule X4) enforces the agreement.

NEVER SILENTLY CLOBBER, AND THE CHECK IS ATOMIC. A name that already exists
gets the `-<n>` disambiguator record_schema.md 3 defines -- `-2`, `-3`, ...
assigned only on collision, never pre-emptively. That is pcrec
`compare.sh:1211-1217`'s rule carried over, and the reason is the same:
losing a baseline snapshot is exactly how a regression goes unnoticed.

The name is CLAIMED with `O_CREAT|O_EXCL` rather than tested with
`os.path.exists`, because an exists-then-write pair is a race: two harness
invocations measuring the same cell in the same second both see the name
free, both write it, and one silently overwrites the other -- the exact
outcome the disambiguator exists to prevent, reintroduced by the way it was
checked. `O_EXCL` makes the claim and the test one operation, so the loser of
the race gets EEXIST and moves on to `-2`.

A RECORD THAT FAILS VALIDATION IS NEVER WRITTEN (contract 4 step 5): the
failure is a harness bug, and a store of records the shared validator rejects
is worse than no store.

TWO TIERS, TWO KINDS OF STORE (schema v1.2, record_schema.md 6.8; Frank's
I-4). The CANONICAL store is the tree carrying a `.canonical` marker file --
the repo's `store/`, from the main tree or any worktree's checkout of it. A
SCRATCH store is any other root; the default one is
`$PCRECBENCH_SCRATCH_STORE` or `build/scratch-store/` (gitignored). A
`tier: scratch` record is REFUSED into the canonical store on write
(`write()`), and `index()` of the canonical store REFUSES to list one that
somehow got there -- belt and braces, because "a scratch number never enters
store/index.tsv or the rankings" is a promise the store keeps, not one the
harness is trusted with. The marker is a file rather than a path comparison
so the rule holds from a worktree without asking git.
"""

import json
import os
import subprocess
import sys
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_STORE = os.path.join(REPO_ROOT, "store")
VALIDATE_PY = os.path.join(REPO_ROOT, "schema", "validate.py")

# The tiers (record_schema.md 6.8). An ABSENT `tier` on a record is `pinned`.
TIER_PINNED = "pinned"
TIER_SCRATCH = "scratch"
TIERS = (TIER_PINNED, TIER_SCRATCH)
CANONICAL_MARKER = ".canonical"
SCRATCH_STORE_ENV = "PCRECBENCH_SCRATCH_STORE"
DEFAULT_SCRATCH_STORE = os.path.join(REPO_ROOT, "build", "scratch-store")

INDEX_HEADER = ("path\tsubbench\tversion\ttestee_id\tmachine_id\ttimestamp"
                "\tstatus\trows\n")

# Per-write staging directories live inside the record directory (so the
# final `os.replace` is a same-filesystem rename) and are skipped by
# `iter_records`. One per write, never shared -- see `write()`.
STAGING_PREFIX = ".staging-"


class StoreError(Exception):
    pass


# ------------------------------------------------------------------- tiers

def is_canonical(store_root):
    """Is this root the CANONICAL store? True iff it carries the marker."""
    return os.path.exists(os.path.join(store_root, CANONICAL_MARKER))


def scratch_store():
    """The default SCRATCH store root: `$PCRECBENCH_SCRATCH_STORE`, else
    `build/scratch-store/` under this tree (gitignored with the rest of
    build/)."""
    return os.environ.get(SCRATCH_STORE_ENV) or DEFAULT_SCRATCH_STORE


def default_store_for(tier):
    """Where a record of this tier goes when nobody said: the canonical store
    for `pinned`, the scratch store for `scratch`."""
    return scratch_store() if tier == TIER_SCRATCH else DEFAULT_STORE


def record_tier(setup):
    return setup.get("tier", TIER_PINNED)


def check_tier_allowed(store_root, tier):
    """Refuse a scratch record into the canonical store. Called by `write()`
    and, EARLY, by the harness -- before the gate, before the machine
    registry, before a single driver runs -- so a refused run costs nothing
    and touches nothing."""
    if tier not in TIERS:
        raise StoreError("unknown record tier %r (the tiers are %s)"
                         % (tier, ", ".join(TIERS)))
    if tier == TIER_SCRATCH and is_canonical(store_root):
        raise StoreError(
            "REFUSED: a `tier: scratch` record can never enter the CANONICAL "
            "store (%s carries the %s marker). Scratch records -- a local "
            "binary, a `quick` cell -- go to a scratch store: omit --store to "
            "use %s, or name any root without the marker "
            "(record_schema.md 6.8; inbox I-4)."
            % (store_root, CANONICAL_MARKER, scratch_store()))


def record_dir(store_root, subbench_id, version, testee_id):
    return os.path.join(store_root, "records",
                        "%s@%s" % (subbench_id, version), testee_id)


def serialize(setup, rows):
    """The record's bytes. Line 1 is the setup object; each row follows.

    `content_hash` must be computed over line 1 WITHOUT that member, so it is
    stamped here rather than by the caller -- one place, and it cannot drift
    from the bytes actually written."""
    from .record import stamp_content_hash
    setup = stamp_content_hash(setup, rows)
    parts = [json.dumps(setup, sort_keys=True, separators=(",", ":"),
                        ensure_ascii=False)]
    parts += [json.dumps(r, sort_keys=True, separators=(",", ":"),
                         ensure_ascii=False) for r in rows]
    return "\n".join(parts) + "\n", setup


MAX_DISAMBIGUATOR = 1000


def claim_path(store_root, setup):
    """ATOMICALLY claim the path for this record. Returns (path, record_id, fd).

    The claim is `O_CREAT|O_EXCL` on the final name; on EEXIST the `-<n>`
    disambiguator is applied and the claim retried. The returned fd owns a
    zero-length file at `path` -- the caller writes the content elsewhere,
    validates it, and `os.replace`s it over this name, which is atomic and
    keeps the exclusivity already won.

    `record_id` may differ from the caller's if a collision forced a suffix,
    and the caller MUST re-stamp it before serialising: the id is inside line
    1 and therefore inside the content hash."""
    sb = setup["subbench"]
    base = setup["record_id"]
    d = record_dir(store_root, sb["id"], sb["version"],
                   setup["testee"]["testee_id"])
    os.makedirs(d, exist_ok=True)
    for n in range(1, MAX_DISAMBIGUATOR + 1):
        rid = base if n == 1 else "%s-%d" % (base, n)
        path = os.path.join(d, rid + ".jsonl")
        try:
            fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
        except FileExistsError:
            continue
        return path, rid, fd
    raise StoreError(
        "%s already holds %d records of this cell at this timestamp -- "
        "refusing to keep counting. Something is re-running one cell in a "
        "loop." % (d, MAX_DISAMBIGUATOR))


def validate_file(path, python=None):
    """Run the SHARED validator (schema/validate.py) with `--check-filename`.
    Returns (ok, output)."""
    proc = subprocess.run([python or sys.executable, VALIDATE_PY,
                           "--check-filename", path],
                          capture_output=True, text=True,
                          env=dict(os.environ, LC_ALL="C"), timeout=300)
    return proc.returncode == 0, (proc.stdout or "") + (proc.stderr or "")


def write(store_root, setup, rows, validate=True):
    """Write one record. -> (path, record_id).

    Three steps, in this order, and the order is the point:

      1. CLAIM the final name with O_EXCL (`claim_path`). From here on no
         other invocation can take it, whatever it does next.
      2. Write the content to `<a PRIVATE staging dir>/<the final basename>`
         and validate it THERE. The basename has to be the final one because
         rule X4 compares it against `record_id`; the staging dirs are
         excluded from `iter_records`, so a half-written or rejected file is
         never visible as a record.

         The staging directory is created by `mkdtemp` and is PRIVATE to one
         write. A single shared `.validating/` was tried first and is wrong:
         concurrent writers each finish and `rmdir` it, pulling the directory
         out from under a writer that has claimed its name but not yet
         written. MEASURED with 8 forked writers racing on one cell -- 6
         records landed, 2 died, and the un-suffixed name was lost.
      3. `os.replace` it over the claimed name -- atomic, and the claim is
         still ours.

    A record that fails validation is never written (harness contract 4 step
    5): the claimed name is released and the rejected bytes are kept under a
    `.rejected` suffix for the person who has to fix the harness bug.

    Step 0, before any of that: a `tier: scratch` record is REFUSED into the
    canonical store (`check_tier_allowed`), before a name is claimed."""
    check_tier_allowed(store_root, record_tier(setup))
    path, rid, fd = claim_path(store_root, setup)
    claimed = True
    checkdir = None
    try:
        if rid != setup["record_id"]:
            setup = dict(setup, record_id=rid)
        text, setup = serialize(setup, rows)

        checkdir = tempfile.mkdtemp(dir=os.path.dirname(path),
                                    prefix=STAGING_PREFIX)
        checkpath = os.path.join(checkdir, os.path.basename(path))
        with open(checkpath, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())

        if validate:
            ok, out = validate_file(checkpath)
            if not ok:
                keep = checkpath + ".rejected"
                os.replace(checkpath, keep)
                raise StoreError(
                    "the record FAILED validation and was NOT written to the "
                    "store -- this is a harness bug, not a measurement result "
                    "(harness contract 4 step 5).\nThe rejected record is at "
                    "%s\n%s" % (keep, out))

        os.replace(checkpath, path)
        claimed = False          # the claim is now the record
        _fsync_dir(os.path.dirname(path))
        return path, rid
    finally:
        os.close(fd)
        if checkdir:
            try:
                os.rmdir(checkdir)      # ours alone; never another writer's
            except OSError:
                pass
        if claimed:
            # Release the zero-length claim: leaving it would put a file in
            # the store that `index` cannot parse. This is the one moment
            # another invocation could take the name -- acceptable, because
            # reaching here at all means the harness is already broken.
            try:
                os.unlink(path)
            except OSError:
                pass


def _fsync_dir(path):
    """Durability of the RENAME, not just of the bytes: on POSIX the directory
    entry needs its own fsync or a crash can lose a file whose contents were
    safely on disk."""
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    except OSError:
        return
    try:
        os.fsync(fd)
    except OSError:
        pass
    finally:
        os.close(fd)


# ------------------------------------------------------------------- index

def iter_records(store_root):
    root = os.path.join(store_root, "records")
    if not os.path.isdir(root):
        return
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames
                             if not d.startswith(STAGING_PREFIX))
        for fn in sorted(filenames):
            if fn.endswith(".jsonl"):
                yield os.path.join(dirpath, fn)


def index(store_root):
    """Regenerate `<store>/index.tsv`: one line per record. Committed with the
    records of the canonical store, so a reader can find a cell without
    opening every file; a scratch store gets its own index the same way.

    The CANONICAL store's index REFUSES to list a `tier: scratch` record.
    `write()` already refuses to put one there, so reaching this is a sign
    something wrote around the store -- and the index, which is what the
    reporter and the rankings read, must not launder it."""
    canonical = is_canonical(store_root)
    lines = [INDEX_HEADER]
    n = 0
    for path in iter_records(store_root):
        with open(path, "r", encoding="utf-8") as f:
            first = f.readline()
            nrows = sum(1 for _ in f)
        try:
            setup = json.loads(first)
        except json.JSONDecodeError:
            raise StoreError("%s: line 1 is not JSON -- the store holds a "
                             "file that is not a record" % path)
        if canonical and record_tier(setup) == TIER_SCRATCH:
            raise StoreError(
                "REFUSED to index %s: it is a `tier: scratch` record inside "
                "the CANONICAL store (%s carries %s). Nothing writes a "
                "scratch record here through store.write(), so it arrived "
                "some other way; move it to a scratch store (%s) -- the "
                "index will not list it and the rankings must never see it "
                "(record_schema.md 6.8)."
                % (path, store_root, CANONICAL_MARKER, scratch_store()))
        rel = os.path.relpath(path, store_root)
        lines.append("%s\t%s\t%s\t%s\t%s\t%s\t%s\t%d\n" % (
            rel, setup["subbench"]["id"], setup["subbench"]["version"],
            setup["testee"]["testee_id"], setup["environment"]["machine_id"],
            setup["run"]["timestamp"], setup["status"], nrows))
        n += 1
    os.makedirs(store_root, exist_ok=True)
    with open(os.path.join(store_root, "index.tsv"), "w",
              encoding="utf-8", newline="\n") as f:
        f.writelines(lines)
    return n
