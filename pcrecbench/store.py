"""store.py -- the record store: the path rule, the never-clobber rule, and
the index (OD-B6, harness contract 4).

    store/
      machines.tsv                       the machine registry (env.py, 6.5)
      index.tsv                          regenerated by `pcrecbench index`
      records/<subbench>@<version>/<testee_id>/<record_id>.jsonl

The FILE NAME IS THE RECORD ID (record_schema.md 2), so the tree is
self-describing: a record can be identified from its path alone, and
`validate.py --check-filename` (rule X4) enforces the agreement.

NEVER SILENTLY CLOBBER. A name that already exists gets the `-<n>`
disambiguator record_schema.md 3 defines -- `-2`, `-3`, ... assigned only on
collision, never pre-emptively. That is pcrec `compare.sh:1211-1217`'s rule
carried over, and the reason is the same: losing a baseline snapshot is
exactly how a regression goes unnoticed.

A RECORD THAT FAILS VALIDATION IS NEVER WRITTEN (contract 4 step 5): the
failure is a harness bug, and a store of records the shared validator rejects
is worse than no store.
"""

import json
import os
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_STORE = os.path.join(REPO_ROOT, "store")
VALIDATE_PY = os.path.join(REPO_ROOT, "schema", "validate.py")

INDEX_HEADER = ("path\tsubbench\tversion\ttestee_id\tmachine_id\ttimestamp"
                "\tstatus\trows\n")


class StoreError(Exception):
    pass


def record_dir(store_root, subbench_id, version, testee_id):
    return os.path.join(store_root, "records",
                        "%s@%s" % (subbench_id, version), testee_id)


def serialize(setup, rows):
    """The record's bytes. Line 1 is the setup object; each row follows.

    `content_hash` must be computed over line 1 WITHOUT that member, so it is
    stamped here rather than by the caller -- one place, and it cannot drift
    from the bytes actually written."""
    from .record import stamp_content_hash
    setup = stamp_content_hash(setup, rows)
    parts = [json.dumps(setup, sort_keys=True, separators=(",", ":"),
                        ensure_ascii=False)]
    parts += [json.dumps(r, sort_keys=True, separators=(",", ":"),
                         ensure_ascii=False) for r in rows]
    return "\n".join(parts) + "\n", setup


def allocate_path(store_root, setup):
    """The path for this record, with the `-<n>` disambiguator applied.
    Returns (path, record_id) -- `record_id` may differ from the caller's if a
    collision forced a suffix, and the caller MUST re-stamp it."""
    sb = setup["subbench"]
    base = setup["record_id"]
    d = record_dir(store_root, sb["id"], sb["version"],
                   setup["testee"]["testee_id"])
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, base + ".jsonl")
    if not os.path.exists(path):
        return path, base
    n = 2
    while True:
        rid = "%s-%d" % (base, n)
        path = os.path.join(d, rid + ".jsonl")
        if not os.path.exists(path):
            return path, rid
        n += 1


def validate_file(path, python=None):
    """Run the SHARED validator (schema/validate.py) with `--check-filename`.
    Returns (ok, output)."""
    proc = subprocess.run([python or sys.executable, VALIDATE_PY,
                           "--check-filename", path],
                          capture_output=True, text=True,
                          env=dict(os.environ, LC_ALL="C"), timeout=300)
    return proc.returncode == 0, (proc.stdout or "") + (proc.stderr or "")


def write(store_root, setup, rows, validate=True):
    """Write one record. -> (path, record_id).

    The record is written to a TEMPORARY name, validated there, and only then
    moved into place, so a rejected record never appears in the store even
    for an instant."""
    path, rid = allocate_path(store_root, setup)
    if rid != setup["record_id"]:
        setup = dict(setup, record_id=rid)
    text, setup = serialize(setup, rows)

    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if validate:
        # validate.py's X4 compares the BASENAME, so the temp file has to
        # carry the final name while it is checked.
        checkdir = os.path.join(os.path.dirname(path), ".validating")
        os.makedirs(checkdir, exist_ok=True)
        checkpath = os.path.join(checkdir, os.path.basename(path))
        os.replace(tmp, checkpath)
        ok, out = validate_file(checkpath)
        if not ok:
            keep = checkpath + ".rejected"
            os.replace(checkpath, keep)
            raise StoreError(
                "the record FAILED validation and was NOT written to the "
                "store -- this is a harness bug, not a measurement result "
                "(harness contract 4 step 5).\nThe rejected record is at %s\n"
                "%s" % (keep, out))
        os.replace(checkpath, path)
        try:
            os.rmdir(checkdir)
        except OSError:
            pass
    else:
        os.replace(tmp, path)
    return path, rid


# ------------------------------------------------------------------- index

def iter_records(store_root):
    root = os.path.join(store_root, "records")
    if not os.path.isdir(root):
        return
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != ".validating")
        for fn in sorted(filenames):
            if fn.endswith(".jsonl"):
                yield os.path.join(dirpath, fn)


def index(store_root):
    """Regenerate `store/index.tsv`: one line per record. Committed with the
    records, so a reader can find a cell without opening every file."""
    lines = [INDEX_HEADER]
    n = 0
    for path in iter_records(store_root):
        with open(path, "r", encoding="utf-8") as f:
            first = f.readline()
            nrows = sum(1 for _ in f)
        try:
            setup = json.loads(first)
        except json.JSONDecodeError:
            raise StoreError("%s: line 1 is not JSON -- the store holds a "
                             "file that is not a record" % path)
        rel = os.path.relpath(path, store_root)
        lines.append("%s\t%s\t%s\t%s\t%s\t%s\t%s\t%d\n" % (
            rel, setup["subbench"]["id"], setup["subbench"]["version"],
            setup["testee"]["testee_id"], setup["environment"]["machine_id"],
            setup["run"]["timestamp"], setup["status"], nrows))
        n += 1
    os.makedirs(store_root, exist_ok=True)
    with open(os.path.join(store_root, "index.tsv"), "w",
              encoding="utf-8", newline="\n") as f:
        f.writelines(lines)
    return n
