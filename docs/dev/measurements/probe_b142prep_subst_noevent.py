"""docs/dev/measurements/probe_b142prep_subst_noevent.py -- [B142] (lane
b142prep, 2026-10-25, inbox I-158/I-159): is [M4-SUBST] (merge 9ae59f5d4,
lane/substland) really NOT an abi event? pcrec says "0 byte diffs over 112
compiles". Here: every bench pattern x {plain, whole} x {caps, nocaps}
(`-e utf8` on the utf8 set) emitted at 9ae59f5d4 AND at its first parent
600111e4e (main before the merge, already abi 84), compared RAW (the whole
.c + .h text, comments included via -fcomments, nothing normalized except
the one `Generated by pcrec` provenance line that names the commit).

    python3 docs/dev/measurements/probe_b142prep_subst_noevent.py OUT.txt
"""
import concurrent.futures as cf, os, re, subprocess, sys, tempfile
sys.path.insert(0, os.getcwd()); sys.path.insert(0, os.path.join(os.getcwd(), "tools"))
sys.argv, OUT = [sys.argv[0], "/var/tmp/pcrecbench/b142prep/edgetmp"], sys.argv[1]
import probe_b142prep_emit as E                       # noqa: E402
import program_identity as PI                          # noqa: E402
B = "/home/pcrec/projects/pcrec-bench/build"
BIN = {p: os.path.join(B, "pcrec-%s/build/pcrec" % p) for p in ("600111e4e", "9ae59f5d4")}
GEN = re.compile(r"^/\* Generated by pcrec.*\*/\s*$", re.M)


def one(job):
    sid, pid, cfg, form, flags, pat = job
    t = {}
    for p, b in BIN.items():
        with tempfile.TemporaryDirectory(dir=E.OUT) as tmp:
            x = PI.emit(b, "--pattern", flags + ["-fcomments"], pat, tmp)
        t[p] = None if x is None else GEN.sub("", x)
    a, b = t["600111e4e"], t["9ae59f5d4"]
    v = "refused-both" if a is None and b is None else (
        "refusal-mover" if a is None or b is None else ("identical" if a == b else "DIFFERS"))
    return (sid, pid, cfg, form, v, len(a or ""), len(b or ""))


jobs = E.population()
with cf.ThreadPoolExecutor(6) as ex:
    rows = list(ex.map(one, jobs))
import collections
c = collections.Counter(r[4] for r in rows)
with open(OUT, "w") as fh:
    fh.write("# probe_b142prep_subst_noevent.py: 600111e4e (pre-merge main) vs 9ae59f5d4, %d compiles\n" % len(rows))
    fh.write("# verdicts: %s\n" % dict(c))
    for r in rows:
        if r[4] not in ("identical", "refused-both"):
            fh.write("\t".join(map(str, r)) + "\n")
print(dict(c))
