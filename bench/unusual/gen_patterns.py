def render_toml(ms):
    out = [TOML_HEAD.replace("@NPAT@", str(len(ms)))]
    for m in ms:
        tags = list(m.tags) + ["requires-" + r for r in m.req]
        out.append("\n[[patterns]]\n")
        out.append("name = %s\n" % toml_str(m.id))
        out.append("file = %s\n" % toml_str("patterns/%s.rx" % m.id))
        out.append('feature_tier = "base"\n')
        out.append('hazard_class = "none"\n')
        out.append("size_class = %s\n" % toml_str(m.size))
        out.append('convention = "perl-leftmost-first"\n')
        out.append("tags = [%s]\n" % ", ".join(toml_str(t) for t in tags))
        out.append("role = %s\n" % toml_str(m.role))
    return "".join(out).encode("utf-8")


def outputs():
    MB.check_cscan_source()
    ms = MB.members()
    outs = {os.path.join("patterns", m.id + ".rx"): m.text for m in ms}
    outs["provenance.tsv"] = render_provenance(ms)
    outs["patterns.rxt"] = render_rxt()
    outs["subbench.toml"] = render_toml(ms)
    return outs


def main(argv):
    check = "--check" in argv
    outs = outputs()
    bad = 0
    os.makedirs(os.path.join(HERE, "patterns"), exist_ok=True)
    for rel, data in sorted(outs.items()):
        path = os.path.join(HERE, rel)
        if check:
            have = open(path, "rb").read() if os.path.exists(path) else None
            if have != data:
                bad += 1
                sys.stderr.write("DIFF %s\n" % rel)
        else:
            with open(path, "wb") as f:
                f.write(data)
    if check:
        extra = set(os.listdir(os.path.join(HERE, "patterns"))) - {os.path.basename(r) for r in outs if r.startswith("patterns")}
        for e in sorted(extra):
            bad += 1
            sys.stderr.write("STRAY patterns/%s\n" % e)
        print("gen_patterns --check: %d file(s), %d difference(s)" % (len(outs), bad))
        return 1 if bad else 0
    print("wrote %d files" % len(outs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
