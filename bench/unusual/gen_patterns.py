#!/usr/bin/env python3
"""gen_patterns.py -- writes (or --check re-derives) everything DERIVED from
the member table (members.py): patterns/*.rx, provenance.tsv, patterns.rxt
(the `ext bench` capability matrix only) and subbench.toml.

    python3 -I bench/unusual/gen_patterns.py            # write
    python3 -I bench/unusual/gen_patterns.py --check    # re-derive + diff

The sidecar's `[[patterns]]` array is the pattern SOURCE of this set at
v0.1 (rxt_source is not declared: pattern blocks in a .rxt would have to
carry `${...}` text and a callout string through pcrec's --list-source
loader, and the capability vocabulary does not know the vars / unusual-*
tokens yet -- L1). patterns.rxt carries ONLY the `ext bench` matrix, copied
verbatim from bench/capability/patterns.rxt for the library roster (so an
engine fact is declared in one place); `--check` fails if the capability
set's blocks drift from the copies.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import members as MB  # noqa: E402

CAP_RXT = os.path.join(os.path.dirname(HERE), "capability", "patterns.rxt")
ROSTER = ["pcre2-interp", "pcre2-jit", "pcrec-auto", "pcrec-nocaps", "pcrec-vm",
          "pcrec-vm-in", "re2-default", "onig-default", "vectorscan-block-som",
          "rust-default"]

# [B148] L4: the `deep` limits arms (docs/design/unusual_set_v1.md 6.1-6.2) are
# the SAME engine as their default sibling under a different limits
# configuration, so they declare the sibling's capability block verbatim (an
# engine fact is still declared in one place). Appended after ROSTER.
DEEP_ARMS = [("pcre2-interp-deep", "pcre2-interp"), ("pcre2-jit-deep", "pcre2-jit"),
             ("pcrec-auto-deep", "pcrec-auto"), ("pcrec-vm-deep", "pcrec-vm"),
             ("onig-default-deep", "onig-default")]

VOCAB_REQUIRES = {"backrefs", "lookaround", "lookbehind-variable", "possessive-quantifier",
                  "atomic-group", "recursion", "conditionals", "k-reset", "control-verbs",
                  "unicode-properties", "named-groups", "free-spacing", "callouts",
                  "span-reporting", "non-utf8-subject", "captures", "true-end-anchor"}


def capability_blocks():
    """-> {testee_id: [token lines]} read from bench/capability/patterns.rxt."""
    out, cur = {}, None
    with open(CAP_RXT, "r", encoding="utf-8", errors="surrogateescape") as f:
        in_ext = False
        for line in f:
            if line.startswith("ext bench"):
                in_ext = True
                continue
            if in_ext and line[:1] not in (" ", "\t", "\n"):
                break
            m = re.match(r"^  capabilities (\S+)\s*$", line)
            if m:
                cur = m.group(1)
                out[cur] = []
            elif cur and line.startswith("    "):
                out[cur].append(line.strip())
    return out


def render_rxt():
    blocks = capability_blocks()
    lines = [
        "description |",
        "  bench/unusual@0.1 -- the unusual-features set. This file carries ONLY the",
        "  `ext bench` capability matrix (the pattern source is subbench.toml's",
        "  [[patterns]] array + patterns/*.rx); every block below is a verbatim copy of",
        "  bench/capability/patterns.rxt's, so an engine fact is declared in one place",
        "  (gen_patterns.py --check). The `callouts` token is declared for libpcre2 only:",
        "  pcrec's callout binding and Oniguruma's `(?{N})` spelling are L5's to declare;",
        "  the vars / unusual-<member> tokens are declared by L5/L7 (patterns carry them as requires-*).",
        "",
        "oracle pcre2",
        "tag set=unusual, version=0.1",
        "ext bench",
        "  roster " + " ".join(ROSTER + [d for d, _ in DEEP_ARMS]),
    ]
    for t, src in [(t, t) for t in ROSTER] + DEEP_ARMS:
        lines.append("  capabilities " + t)
        for tok in blocks[src]:
            assert tok in VOCAB_REQUIRES, tok
            lines.append("    " + tok)
    return ("\n".join(lines) + "\n").encode("utf-8")


def tsv_cell(s):
    return s.replace("\t", " ").replace("\n", " ")


def render_provenance(ms):
    head = ("pattern_id\tfamily\tprovenance_source\tsource_url\tsource_ref\tlicense\tlicense_note\t"
            "retrieved\tfidelity\tadaptation\tattribution\ttwin_of\tisolates\n")
    rows = []
    for m in ms:
        p = m.prov
        rows.append("\t".join(tsv_cell(x) for x in (
            m.id, m.family, p["src"], p["url"], p["ref"], p["lic"], p["lic_note"],
            "2026-10-27", p["fid"], p["adapt"], p["attr"], m.twin_of, m.isolates)) + "\n")
    return (head + "".join(rows)).encode("utf-8")


def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


